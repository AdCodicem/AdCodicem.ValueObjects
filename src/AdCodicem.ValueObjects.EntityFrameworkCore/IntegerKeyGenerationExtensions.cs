using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace AdCodicem.ValueObjects.EntityFrameworkCore;

// HasValueObjectKeyGeneration is declared once per underlying type it supports, each in a class of its own: C# cannot
// declare in one class two methods that differ only by their constraints, and drops from overload resolution a candidate
// whose constraints fail, so that a call names no type argument and picks the one declared for its key's type. A value
// object over another type is a compile error.

/// <summary>
/// Generates a key over a 16-bit integer the way the provider generates a <see cref="short"/> key.
/// </summary>
public static class ValueObjectInt16KeyGenerationExtensions
{
    /// <summary>
    /// Has the database generate the key when an entity is added: an identity column on SQL Server and PostgreSQL, the
    /// row identifier on SQLite, with a temporary value in the change tracker until the row is saved.
    /// </summary>
    /// <typeparam name="TSelf">Value object type, over <see cref="short"/>.</typeparam>
    /// <param name="builder">Property builder of the key.</param>
    /// <returns>The same builder, so calls can be chained.</returns>
    /// <remarks>
    /// On SQL Server and PostgreSQL, the column is a <c>smallint</c> identity, whose values the value object's type can
    /// hold; on SQLite, the key is the row identifier, a 64-bit integer, which outgrows the type past
    /// <see cref="short.MaxValue"/>. See
    /// <see cref="ValueObjectInt32KeyGenerationExtensions.HasValueObjectKeyGeneration{TSelf}(PropertyBuilder{TSelf})"/>
    /// for what generation changes.
    /// </remarks>
    public static PropertyBuilder<TSelf> HasValueObjectKeyGeneration<TSelf>(this PropertyBuilder<TSelf> builder)
        where TSelf : struct, IValueObject<TSelf, short>
        => KeyGeneration.Configure<TSelf, short>(builder);
}

/// <summary>
/// Generates a key over a 32-bit integer the way the provider generates an <see cref="int"/> key.
/// </summary>
public static class ValueObjectInt32KeyGenerationExtensions
{
    /// <summary>
    /// Has the database generate the key when an entity is added: an identity column on SQL Server and PostgreSQL, the
    /// row identifier on SQLite, with a temporary value in the change tracker until the row is saved.
    /// </summary>
    /// <typeparam name="TSelf">Value object type, over <see cref="int"/>.</typeparam>
    /// <param name="builder">Property builder of the key.</param>
    /// <returns>The same builder, so calls can be chained.</returns>
    /// <remarks>
    /// <para>
    /// The key becomes generated on add, as an <see cref="int"/> key is by convention, and gets the generator of
    /// <see cref="ValueObjectKeyGeneratorFactory{TSelf, TValue}"/>, which a compiled model can write. The column becomes
    /// an <c>IDENTITY</c> on SQL Server, a <c>GENERATED BY DEFAULT AS IDENTITY</c> on PostgreSQL, and stays an
    /// <c>INTEGER PRIMARY KEY</c>, the row identifier, on SQLite, which reuses the highest key once it is deleted unless
    /// the property also calls SQLite's <c>UseAutoincrement()</c>: unlike a key of the <see cref="int"/> itself, which
    /// is <c>AUTOINCREMENT</c> there by convention.
    /// </para>
    /// <para>
    /// Until <c>SaveChanges</c>, the change tracker holds a temporary value, negative and never written, and the
    /// entity's property its default; the key the database generates then takes its place, read through the converter,
    /// so a type counted from one accepts it, in a strict context too. Zero, the default, is generated over; any other
    /// key the domain set is kept, which SQL Server then refuses to insert into an identity column, and PostgreSQL
    /// stores. Only a relational database generates the key: on another provider, Entity Framework Core's in-memory
    /// database for one, adding an entity without its key throws an <see cref="InvalidOperationException"/>, rather
    /// than store the temporary value as the key.
    /// </para>
    /// <para>
    /// SQL Server cannot alter an existing column into an identity column: a migration from a model where the key was
    /// not generated fails, and the table has to be created again. On PostgreSQL, such a migration starts the identity
    /// at one, below the keys the table already holds.
    /// </para>
    /// </remarks>
    public static PropertyBuilder<TSelf> HasValueObjectKeyGeneration<TSelf>(this PropertyBuilder<TSelf> builder)
        where TSelf : struct, IValueObject<TSelf, int>
        => KeyGeneration.Configure<TSelf, int>(builder);
}

