using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Metadata.Conventions;

namespace AdCodicem.ValueObjects.EntityFrameworkCore;

/// <summary>
/// Gives a primary key over a <see cref="Guid"/> value object that nothing generates the generator of
/// <see cref="UnassignedValueObjectKeyGeneratorFactory"/>, which refuses an entity added without it.
/// </summary>
/// <remarks>
/// <para>
/// Entity Framework Core generates a <see cref="Guid"/> key when an entity is added, but a key typed as a value object
/// over <see cref="Guid"/> is neither generated nor checked: an entity added without it would be stored with
/// <see cref="Guid.Empty"/>, which a value object without a rule against it accepts, and the next one would fail on the
/// duplicate key.
/// </para>
/// <para>
/// Only the primary key of one property is concerned, an alternate key being left alone, which is no foreign key, and
/// which nothing generates: its value generation was configured neither by the application nor by a data annotation,
/// Entity Framework Core gave it none, for a database default for instance, and no generator was set, by the
/// application or by another convention. A dependent sharing its principal's key, an owned reference type among them,
/// is left to its principal; an owned collection item with a key of its own is refused as an entity is. The key stays
/// <see cref="ValueGenerated.Never"/>: Entity Framework Core calls a property's generator whenever it has one, so
/// neither the column nor the migration snapshot changes.
/// </para>
/// <para>
/// A value object is told by the interface it implements, <see cref="IValueObject{TValue}"/> of <see cref="Guid"/>,
/// generated, generic or written by hand alike, and the factory is named by a type that is not generic: nothing is closed
/// at run time, and the registry is not read.
/// </para>
/// </remarks>
internal sealed class ValueObjectKeyConvention : IModelFinalizingConvention
{
    /// <inheritdoc />
    public void ProcessModelFinalizing(
        IConventionModelBuilder modelBuilder,
        IConventionContext<IConventionModelBuilder> context)
    {
        // A derived type finds the key of the root of its hierarchy, whose generator is then set already.
        foreach (var entityType in modelBuilder.Metadata.GetEntityTypes())
        {
            if (entityType.FindPrimaryKey() is { Properties: [var property] } && IsUngenerated(property))
            {
                property.Builder.HasValueGeneratorFactory(typeof(UnassignedValueObjectKeyGeneratorFactory));
            }
        }
    }

    /// <summary>
    /// Tells whether a key is over a <see cref="Guid"/> value object, no foreign key, and generated by nothing.
    /// </summary>
    private static bool IsUngenerated(IConventionProperty property)
        => !property.IsForeignKey()
           && property.ValueGenerated == ValueGenerated.Never
           && property.GetValueGeneratedConfigurationSource() is not (ConfigurationSource.Explicit or ConfigurationSource.DataAnnotation)
           && property.GetValueGeneratorFactoryConfigurationSource() is null
           && property.ClrType.IsAssignableTo(typeof(IValueObject<Guid>));
}
