    public void A_migration_records_the_identity_of_an_integer_key_and_nothing_for_a_Guid_key()
    {
        using var before = new UnrefusedMigrationContext();
        using var refused = new RefusedMigrationContext();
        using var generated = new GeneratedMigrationContext();
        var differ = before.GetService<IMigrationsModelDiffer>();

        differ.HasDifferences(RelationalModel(before), RelationalModel(refused)).Should().BeFalse("the refusal changes no column");
        var operations = differ.GetDifferences(RelationalModel(refused), RelationalModel(generated));

        var alter = operations.Should().ContainSingle("only the integer key changes").Which.Should().BeOfType<AlterColumnOperation>().Which;
        alter.Table.Should().Be(nameof(Folio));
        alter.Name.Should().Be(nameof(Folio.Id));
        alter["Npgsql:ValueGenerationStrategy"].Should().Be(NpgsqlValueGenerationStrategy.IdentityByDefaultColumn);
        alter.OldColumn["Npgsql:ValueGenerationStrategy"].Should().BeNull();

        static IRelationalModel RelationalModel(DbContext context) => context.GetService<IDesignTimeModel>().Model.GetRelationalModel();
    }

