        }

        NpgsqlPropertyExtensions.GetValueGenerationStrategy(Key<Plain>(model))
            .Should().Be(NpgsqlValueGenerationStrategy.None, "a key over an integer nothing generates stays a plain column");
    }

    /// <summary>
    /// <c>ConfigureValueObjects</c> gives a key of one property over a <see cref="Guid"/> value object, which is no
    /// foreign key and which nothing generates, a generator that refuses it unset, generated, generic and written by hand
    /// alike, the last mapped one by one and never registered: the convention reads the type, not the registry, and to an
    /// owned collection item with a key of its own, as to an entity. The key stays generated by nothing, so neither the
    /// column nor a migration changes, and a derived type shares the root's.
    /// </summary>
    [Fact]
    public void The_convention_gives_a_Guid_key_nothing_generates_a_generator_that_refuses_it()
    {
        var model = DesignTimeModel(new KeyContext());

        IReadOnlyProperty[] keys =
        [
            Key<Shipment>(model), Key<Client>(model), Key<Box>(model), Key<Bundle>(model), Key<Animal>(model),
            Key<BasketItem>(model),
        ];

        foreach (var key in keys)
        {
            key.ValueGenerated.Should().Be(ValueGenerated.Never, key.DeclaringType.DisplayName());
            key.FindAnnotation("ValueGeneratorFactoryType")!.Value
                .Should().Be(typeof(UnassignedValueObjectKeyGeneratorFactory), key.DeclaringType.DisplayName());
        }

        Key<Dog>(model).Should().BeSameAs(Key<Animal>(model));
        ValueObjectRegistry.TryGet(typeof(Declared<BundleKey, Guid>), out _).Should().BeFalse();
    }

    /// <summary>
    /// The convention leaves alone every key it does not concern: a composite one, none, an alternate key, a foreign key
    /// (a dependent sharing its principal's key, an owned reference type), one the application opted out of generation
    /// explicitly or through a data annotation, one with a database default, one with a generator of its own, one over an
    /// integer value object, over text, and a <see cref="Guid"/> key, which Entity Framework Core generates itself. An
    /// entity whose alternate key is unset is added.
    /// </summary>
    [Fact]
    public void The_convention_leaves_every_other_key_alone()
    {
        using var context = new KeyContext();
        var model = context.GetService<IDesignTimeModel>().Model;
        var address = model.FindEntityType(typeof(Order))!.FindNavigation(nameof(Order.Address))!.TargetEntityType;

        IReadOnlyProperty[] keys =
        [
            .. model.FindEntityType(typeof(Pair))!.FindPrimaryKey()!.Properties,
            model.FindEntityType(typeof(Note))!.FindProperty(nameof(Note.Id))!,
            model.FindEntityType(typeof(Lookup))!.FindProperty(nameof(Lookup.Code))!,
            Key<Profile>(model),
            address.FindPrimaryKey()!.Properties.Single(),
            Key<Legacy>(model),
            Key<Annotated>(model),
            Key<Defaulted>(model),
            Key<Fixed>(model),
            Key<Plain>(model),
            Key<TextKeyed>(model),
            Key<RawKeyed>(model),
        ];

        model.FindEntityType(typeof(Note))!.FindPrimaryKey().Should().BeNull();
        foreach (var key in keys)
        {
            key.FindAnnotation("ValueGeneratorFactoryType")?.Value
                .Should().NotBe(typeof(UnassignedValueObjectKeyGeneratorFactory), $"{key.DeclaringType.DisplayName()}.{key.Name}");
        }

        Key<Defaulted>(model).ValueGenerated.Should().Be(ValueGenerated.OnAdd);
        Key<RawKeyed>(model).ValueGenerated.Should().Be(ValueGenerated.OnAdd);
        Key<Legacy>(model).ValueGenerated.Should().Be(ValueGenerated.Never);
        Key<Fixed>(model).GetValueGeneratorFactory().Should().NotBeNull("the application's own generator is kept");
        var lookup = model.FindEntityType(typeof(Lookup))!;
        lookup.FindKey(lookup.FindProperty(nameof(Lookup.Code))!).Should().NotBeNull("the code is an alternate key");
        context.Add(new Lookup()).State.Should().Be(EntityState.Added, "the refusal is for a primary key");
    }

