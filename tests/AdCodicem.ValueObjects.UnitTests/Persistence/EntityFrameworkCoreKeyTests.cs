    /// <summary>
    /// On SQLite, an integer key is the row identifier, which the database generates, and which the converter reads back
    /// in a strict context, <c>AUTOINCREMENT</c> once the property also calls SQLite's <c>UseAutoincrement()</c>, as a key
    /// of the integer itself is by convention; a GUID key is a version 7 one, and both round-trip.
    /// </summary>
    [Fact]
    public async Task Generated_keys_reach_the_database_and_read_back_through_the_converter()
    {
        var ct = TestContext.Current.CancellationToken;
        Folio[] folios = [new(), new()];
        Journal[] journals = [new(), new()];
        Slot[] slots = [new(), new()];
        var parcel = new Parcel();

        await using (var write = new StrictSqliteKeyContext(_connection))
        {
            var script = write.Database.GenerateCreateScript();
            script.Should().Contain("\"Id\" INTEGER NOT NULL CONSTRAINT \"PK_Journal\" PRIMARY KEY AUTOINCREMENT")
                .And.Contain("\"Id\" INTEGER NOT NULL CONSTRAINT \"PK_Folio\" PRIMARY KEY")
                .And.NotContain("\"PK_Folio\" PRIMARY KEY AUTOINCREMENT")
                .And.Contain("\"Id\" INTEGER NOT NULL CONSTRAINT \"PK_RawNumbered\" PRIMARY KEY AUTOINCREMENT", "a key of the integer itself is");
            await write.Database.EnsureCreatedAsync(ct);
            write.AddRange(folios);
            write.AddRange(journals);
            write.AddRange(slots);
            write.Add(parcel);
            (await write.SaveChangesAsync(ct)).Should().Be(7);
        }

        folios.Select(static folio => folio.Id.Value).Should().Equal(1, 2);
        journals.Select(static journal => journal.Id.Value).Should().Equal(1L, 2L);
        slots.Select(static slot => slot.Id.Value).Should().Equal((short)1, (short)2);
        parcel.Id.Value.Version.Should().Be(7);

        await using var read = new StrictSqliteKeyContext(_connection);
        var second = folios[1].Id;
        (await read.Set<Folio>().SingleAsync(folio => folio.Id == second, ct)).Id.Should().Be(second);
        var key = parcel.Id;
        (await read.Set<Parcel>().CountAsync(entity => entity.Id == key, ct)).Should().Be(1);
    }

