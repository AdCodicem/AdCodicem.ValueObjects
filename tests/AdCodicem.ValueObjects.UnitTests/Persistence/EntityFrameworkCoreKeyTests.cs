    /// <summary>
    /// A dependent whose key holds a foreign key to a key refused unset, a card sharing its locker's key or a slot keyed by
    /// its locker's key and a number, left at its default for the navigation to fill, is taken for a new one when an
    /// aggregate already stored is attached, as for a <see cref="Guid"/> key, since the principal's key now has a
    /// generator, and is tracked as added without being refused: <c>SaveChanges</c> would insert it again. Setting its
    /// foreign key, or its state, by hand, or opting the principal's key out of generation, attaches it unchanged.
    /// </summary>
    [Fact]
    public void A_dependent_keyed_by_its_principals_key_left_to_the_navigation_is_attached_as_added()
    {
        using (var context = new KeyContext())
        {
            var card = new LockerCard();
            var slot = new LockerSlot { Number = 1 };

            context.Attach(new Locker { Id = Assigned, Card = card, Slots = { slot } }).State.Should().Be(EntityState.Unchanged);

            context.Entry(card).State.Should().Be(EntityState.Added, "its key is left to the principal's, which has a generator");
            context.Entry(slot).State.Should().Be(EntityState.Added);
            card.Id.Should().Be(Assigned, "the navigation fills the key in");
            slot.LockerId.Should().Be(Assigned);

            context.Entry(card).State = EntityState.Unchanged;
            context.Entry(card).State.Should().Be(EntityState.Unchanged, "a state set by hand asks no generator");
        }

        using (var context = new KeyContext())
        {
            var card = new LockerCard { Id = Assigned };
            var slot = new LockerSlot { LockerId = Assigned, Number = 1 };

            context.Attach(new Locker { Id = Assigned, Card = card, Slots = { slot } });

            context.Entry(card).State.Should().Be(EntityState.Unchanged, "its foreign key is set");
            context.Entry(slot).State.Should().Be(EntityState.Unchanged);
        }

        using (var context = new OptedOutLockerContext())
        {
            var card = new LockerCard();
            var slot = new LockerSlot { Number = 1 };

            context.Attach(new Locker { Id = Assigned, Card = card, Slots = { slot } });

            context.Entry(card).State.Should().Be(EntityState.Unchanged, "the principal's key has no generator");
            context.Entry(slot).State.Should().Be(EntityState.Unchanged);
        }
    }

