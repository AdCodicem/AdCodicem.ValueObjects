    private static void Refused(Action add, string entity, string key, string type)
    {
        var refusal = add.Should().Throw<InvalidOperationException>().WithMessage(
            $"'{entity}' was added without its key: '{key}' holds default({type}), Guid.Empty, and nothing generates it. "
            + "Assign the key in the domain, or have it generated with HasValueObjectKeyGeneration().").Which;

        ValueObjectErrors.TryGetCode(refusal, out var code).Should().BeTrue();
        code.Should().Be(ValueObjectErrorCodes.Required);
        refusal.Data[ValueObjectErrors.ErrorCodeKey].Should().Be("value_object.required");
    }

