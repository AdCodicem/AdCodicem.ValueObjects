    /// <summary>Maps every key shape on PostgreSQL, whose model building and change tracking open no connection.</summary>
    private class KeyContext : DbContext
    {
        protected virtual bool Strict => false;

        protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder) => optionsBuilder.UseNpgsql("Host=unused");

        protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
            => configurationBuilder.ConfigureValueObjects(Strict);

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<Shipment>();
            modelBuilder.Entity<Client>();
            modelBuilder.Entity<Box>();
            modelBuilder.Entity<Bundle>().Property(static bundle => bundle.Id).HasValueObjectConversion<Declared<BundleKey, Guid>, Guid>();
            modelBuilder.Entity<Animal>();
            modelBuilder.Entity<Dog>();
            modelBuilder.Entity<Parcel>().Property(static parcel => parcel.Id).HasValueObjectKeyGeneration();
            modelBuilder.Entity<Crate>().Property(static crate => crate.Id).HasValueObjectKeyGeneration();
            modelBuilder.Entity<Ticket>().Property(static ticket => ticket.Id).HasValueObjectKeyGeneration();
            modelBuilder.Entity<Folio>().Property(static folio => folio.Id).HasValueObjectKeyGeneration();
            modelBuilder.Entity<Journal>().Property(static journal => journal.Id).HasValueObjectKeyGeneration();
            modelBuilder.Entity<Slot>().Property(static slot => slot.Id).HasValueObjectKeyGeneration();
            modelBuilder.Entity<Plain>();
            modelBuilder.Entity<Pair>().HasKey(static pair => new { pair.A, pair.B });
            modelBuilder.Entity<Note>().HasNoKey();
            modelBuilder.Entity<Profile>().HasOne<Shipment>().WithOne().HasForeignKey<Profile>(static profile => profile.Id);
            modelBuilder.Entity<Order>(order =>
            {
                order.OwnsOne(static entity => entity.Address);
                order.HasMany(static entity => entity.Lines).WithOne().HasForeignKey("OrderId");
            });
            modelBuilder.Entity<Basket>().OwnsMany(static basket => basket.Items, static items => items.HasKey(static item => item.Id));
            modelBuilder.Entity<Locker>(locker =>
            {
                locker.HasOne(static entity => entity.Card).WithOne().HasForeignKey<LockerCard>(static card => card.Id);
                locker.HasMany(static entity => entity.Slots).WithOne().HasForeignKey(static slot => slot.LockerId);
            });
            modelBuilder.Entity<LockerSlot>().HasKey(static slot => new { slot.LockerId, slot.Number });
            modelBuilder.Entity<Lookup>().HasAlternateKey(static lookup => lookup.Code);
            modelBuilder.Entity<Legacy>().Property(static legacy => legacy.Id).ValueGeneratedNever();
            modelBuilder.Entity<Annotated>();
            modelBuilder.Entity<Defaulted>().Property(static defaulted => defaulted.Id).HasDefaultValueSql("gen_random_uuid()");
            modelBuilder.Entity<Fixed>().Property(static entity => entity.Id).HasValueGenerator<FixedParcelIds>();
            modelBuilder.Entity<TextKeyed>();
            modelBuilder.Entity<RawKeyed>();
        }
    }

