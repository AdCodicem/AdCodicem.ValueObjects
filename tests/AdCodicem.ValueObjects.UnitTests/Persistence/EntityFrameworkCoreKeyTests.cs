    /// <summary>
    /// A key over a <see cref="short"/>, an <see cref="int"/> or a <see cref="long"/> becomes PostgreSQL's identity, as a
    /// key of the integer itself would by convention: the provider looks through the converter once the key is generated
    /// on add. Each call picks the method declared for its key's type, with no type argument.
    /// </summary>
    [Fact]
    public void HasValueObjectKeyGeneration_makes_an_integer_key_the_providers_identity()
    {
        var model = DesignTimeModel(new KeyContext());

        GeneratedBy<ValueObjectKeyGeneratorFactory<FolioNumber, int>>(Key<Folio>(model));
        GeneratedBy<ValueObjectKeyGeneratorFactory<LedgerNumber, long>>(Key<Journal>(model));
        GeneratedBy<ValueObjectKeyGeneratorFactory<ShelfNumber, short>>(Key<Slot>(model));

